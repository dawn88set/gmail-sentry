#!/usr/bin/env node
/**
 * Phase 5.7 — dump catalog/INDEX.md + catalog/INDEX.json from the
 * on-disk catalog tree. Run from the seed root:
 *
 *   node scripts/dump-catalog-index.mjs
 *
 * The script is purposely standalone — no NestJS, no TypeScript, no
 * build step — so the seed can regenerate the index without bringing
 * in the platform's dev dependencies. Output is byte-identical to the
 * `CatalogRegistryService.getSummary()` shape used by the planner.
 *
 * **Never includes secret-shaped fields.** Each kind has an explicit
 * pluck list; any unexpected key from a manifest is dropped on the
 * floor so the index stays safe to commit and to ship to authors'
 * AI assistants.
 */

import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import * as path from 'node:path';
import * as url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const catalogRoot = path.resolve(here, '..', 'catalog');

if (!existsSync(catalogRoot)) {
  console.error(`Catalog directory not found at ${catalogRoot}`);
  process.exit(1);
}

// Whitelisted fields per kind. Anything else in the manifest is dropped
// — this is the secret-boundary backstop for the index.
const INTEGRATION_KEYS = [
  'id',
  'version',
  'name',
  'description',
  'category',
  'kind',
  'authType',
  'intentHints',
  'providedToolIds',
];
const TOOL_KEYS = [
  'id',
  'version',
  'description',
  'intentHints',
  'inputs',
  'outputs',
  'providedByIntegration',
];
const AGENT_KEYS = [
  'id',
  'version',
  'description',
  'intentHints',
  'inputs',
  'outputs',
  'defaultTools',
  'defaultIntegrations',
];
const TRIGGER_KEYS = [
  'id',
  'version',
  'kind',
  'description',
  'configFields',
];
const WORKFLOW_KEYS = ['id', 'version', 'description', 'intentHints'];
// Skills are vetted PROCEDURES an author inlines into a custom agent's prompt.
// The index lists the pointer only (id/intent/appliesTo) — the full procedure
// lives in the skill's `procedure.md`, read on demand.
const SKILL_KEYS = [
  'id',
  'version',
  'description',
  'intentHints',
  'appliesTo',
];

function pluck(obj, keys) {
  const out = {};
  for (const k of keys) {
    if (obj[k] !== undefined) out[k] = obj[k];
  }
  return out;
}

function readManifests(kindDir, keys) {
  const result = [];
  if (!existsSync(kindDir)) return result;
  for (const entry of readdirSync(kindDir).sort()) {
    const dir = path.join(kindDir, entry);
    let stat;
    try {
      stat = statSync(dir);
    } catch {
      continue;
    }
    if (!stat.isDirectory()) continue;
    const mf = path.join(dir, 'manifest.json');
    if (!existsSync(mf)) continue;
    try {
      const raw = JSON.parse(readFileSync(mf, 'utf-8'));
      result.push(pluck(raw, keys));
    } catch (e) {
      console.warn(`Skipping ${mf}: ${e?.message ?? e}`);
    }
  }
  return result;
}

const summary = {
  // The version is a stable sha-flavoured tag the planner uses to bust
  // its prompt cache. Here we use a content hash so the index changes
  // exactly when the catalog does — the seed can diff to detect drift.
  generatedAt: new Date().toISOString(),
  integrations: readManifests(path.join(catalogRoot, 'integrations'), INTEGRATION_KEYS),
  tools: readManifests(path.join(catalogRoot, 'tools'), TOOL_KEYS),
  agents: readManifests(path.join(catalogRoot, 'agents'), AGENT_KEYS),
  triggers: readManifests(path.join(catalogRoot, 'triggers'), TRIGGER_KEYS),
  workflows: readManifests(path.join(catalogRoot, 'workflows'), WORKFLOW_KEYS),
  skills: readManifests(path.join(catalogRoot, 'skills'), SKILL_KEYS),
};

const jsonPath = path.join(catalogRoot, 'INDEX.json');
writeFileSync(jsonPath, JSON.stringify(summary, null, 2), 'utf-8');

// Build INDEX.md. Format is optimised for grep — one row per entry —
// since authors (humans and AI) will scan it for an integration id.
const lines = [];
lines.push('# Catalog Index');
lines.push('');
lines.push(
  '_Auto-generated by `scripts/dump-catalog-index.mjs`. Do not edit by hand._',
);
lines.push('');
lines.push(`Generated: ${summary.generatedAt}`);
lines.push('');
lines.push(
  'These integrations are **built in** — the Claritty platform manages OAuth/credentials per user. ' +
    'To use one: declare it in `intelligence.yaml#integrations`, list its tools in the agent, and ' +
    'call them (or `ctx.integration("<id>")`). No API keys, no OAuth code; test locally with ' +
    '`CLARITTY_FAKE_CREDS_<ID>`. See `INTEGRATIONS.md`. A service NOT listed here is not built in — ' +
    'use a custom tool or a clearly-labeled seed, never a faked one.',
);
lines.push('');

function section(title, rows, mkLine) {
  lines.push(`## ${title}`);
  lines.push('');
  if (rows.length === 0) {
    lines.push('_None._');
    lines.push('');
    return;
  }
  for (const r of rows) {
    lines.push(mkLine(r));
  }
  lines.push('');
}

section('Integrations', summary.integrations, (i) => {
  const transport = i.kind ?? 'native';
  const auth = i.authType ?? 'none';
  const cat = i.category ?? 'other';
  const tools = (i.providedToolIds ?? []).join(', ');
  return (
    `- **\`${i.id}\`** _${cat}_ · ${transport} · auth=${auth}` +
    (i.description ? ` — ${i.description}` : '') +
    (tools ? `\n  Tools: ${tools}` : '')
  );
});

section('Tools (catalog)', summary.tools, (t) => {
  const provided = t.providedByIntegration
    ? ` (provided by \`${t.providedByIntegration}\`)`
    : ' (standalone)';
  return `- **\`${t.id}\`**${provided}${t.description ? ` — ${t.description}` : ''}`;
});

section('Agents (catalog)', summary.agents, (a) => {
  const tools = (a.defaultTools ?? []).join(', ');
  const ints = (a.defaultIntegrations ?? []).join(', ');
  let line = `- **\`${a.id}\`**${a.description ? ` — ${a.description}` : ''}`;
  if (tools) line += `\n  Default tools: ${tools}`;
  if (ints) line += `\n  Default integrations: ${ints}`;
  return line;
});

section('Triggers', summary.triggers, (t) => {
  return `- **\`${t.id}\`** _${t.kind ?? '?'}_${t.description ? ` — ${t.description}` : ''}`;
});

section('Workflows (templates)', summary.workflows, (w) => {
  return `- **\`${w.id}\`**${w.description ? ` — ${w.description}` : ''}`;
});

section('Skills (vetted agent procedures)', summary.skills, (s) => {
  // A skill is procedural know-how you INLINE into a custom agent's prompt.md —
  // don't reinvent the procedure freehand. Read `catalog/skills/<id>/procedure.md`.
  const applies = (s.appliesTo ?? []).join(', ');
  return (
    `- **\`${s.id}\`**${s.description ? ` — ${s.description}` : ''}` +
    (applies ? `\n  Fits agents that: ${applies}` : '')
  );
});

writeFileSync(path.join(catalogRoot, 'INDEX.md'), lines.join('\n'), 'utf-8');

console.log(
  `Wrote ${jsonPath} and ${path.join(catalogRoot, 'INDEX.md')} ` +
    `(${summary.integrations.length} integrations, ${summary.tools.length} tools, ` +
    `${summary.agents.length} agents, ${summary.triggers.length} triggers, ` +
    `${summary.workflows.length} workflows, ${summary.skills.length} skills)`,
);
